import React from "react";
import { syntheticDocument } from "@/test/synthetic-company-documents";
import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import {
  AutomaticReview,
  InternalCompanyReview,
  automaticReviewState,
} from "./internal-review-client";

const load = syntheticDocument;
const historical = load("51050532-c7a0-4bf5-bcf7-3d8f5a4d696d");
const failed = load("e182f7bd-c35e-4a8b-afc7-67ff86f21cda");
const savedChoice = load("d4eb59e6-8160-4d45-a8d2-44c0174b7b65");
const historicalBody = historical.review!.emails[0].body.replace(/\s+/g, " ").trim();
beforeEach(() => {
  vi.useFakeTimers({ toFake: ["Date"] });
  vi.setSystemTime(new Date(failed.createdAt));
});
afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
  vi.useRealTimers();
});

it("keeps historical emails out of the current failed result and identifies run/time", async () => {
  vi.stubGlobal(
    "fetch",
    vi.fn(async () =>
      Response.json({
        ok: true,
        aiReady: true,
        documents: [failed, historical],
      }),
    ),
  );
  render(<InternalCompanyReview />);
  await screen.findByText("Current research run");
  expect(screen.getByText(/Evidence rejected — insufficient evidence/)).toBeTruthy();
  expect(screen.getByText(/e182f7bd-c35e-4a8b-afc7-67ff86f21cda/)).toBeTruthy();
  expect(screen.queryByText(historicalBody)).toBeNull();
  expect(screen.queryByText(/Email 1:/)).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Show historical runs and demonstrations" }));
  expect(screen.getByText(historicalBody)).toBeTruthy();
  expect(
    screen.getByText("Historical record — not generated by the current submission"),
  ).toBeTruthy();
});

it("clears old output immediately, polls read-only checkpoints, and never resubmits during drafting", async () => {
  const current = structuredClone(failed);
  current.id = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
  current.automatic!.status = "RUNNING";
  current.automatic!.stage = "SEQUENCE";
  current.automatic!.issues = [];
  let submitted = false;
  let finish!: (response: Response) => void;
  const fetcher = vi.fn(async (_: string, init?: RequestInit) => {
    if (init?.method === "POST") {
      submitted = true;
      return new Promise<Response>((resolve) => {
        finish = resolve;
      });
    }
    return Response.json({
      ok: true,
      aiReady: true,
      documents: submitted ? [current, failed, historical] : [failed, historical],
    });
  });
  vi.stubGlobal("fetch", fetcher);
  render(<InternalCompanyReview />);
  await screen.findByText("Current research run");
  fireEvent.change(screen.getByLabelText("Company name or domain"), {
    target: { value: "nutrafol.com" },
  });
  fireEvent.click(screen.getByRole("button", { name: "Research" }));
  expect(
    screen.getByText("Researching — this submission has no generated drafts yet."),
  ).toBeTruthy();
  expect(screen.queryByText(/e182f7bd-c35e-4a8b-afc7-67ff86f21cda/)).toBeNull();
  await screen.findByText("INTERNAL ONLY · Drafting", {}, { timeout: 4000 });
  current.automatic!.status = "NO_PITCH";
  current.automatic!.issues = ["INSUFFICIENT_COMMERCIAL_EVIDENCE"];
  finish(Response.json({ ok: true, document: current }));
  await screen.findByText("INTERNAL ONLY · Insufficient evidence — NO_PITCH");
  expect(screen.queryByText(historicalBody)).toBeNull();
  expect(fetcher.mock.calls.filter(([, init]) => init?.method === "POST")).toHaveLength(1);
});

it("labels completion as review-required, never approved, and distinguishes review from drafting", () => {
  const result = structuredClone(failed.automatic!);
  result.status = "REVIEW_REQUIRED";
  expect(automaticReviewState(result)).toBe("Completed — human review required");
  result.status = "RUNNING";
  result.stage = "QUALITY_REVIEW";
  expect(automaticReviewState(result)).toBe("Independent review");
  result.stage = "RESEARCH";
  expect(automaticReviewState(result)).toBe("Researching");
});

