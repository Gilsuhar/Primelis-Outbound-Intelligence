it("a failed submission and later refresh never relabel the previous result as the new run", async () => {
  vi.stubGlobal(
    "fetch",
    vi.fn(async (_: string, init?: RequestInit) =>
      init?.method === "POST"
        ? Response.json({ ok: false, message: "Request failed without a result." }, { status: 503 })
        : Response.json({ ok: true, aiReady: true, documents: [failed, historical] }),
    ),
  );
  render(<InternalCompanyReview />);
  await screen.findByText("Current research run");
  fireEvent.change(screen.getByLabelText("Company name or domain"), {
    target: { value: "nutrafol.com" },
  });
  fireEvent.click(screen.getByRole("button", { name: "Research" }));
  await screen.findByText("Request failed without a result.");
  fireEvent.click(screen.getByRole("button", { name: "Refresh internal reviews" }));
  await screen.findByText(/No result for the current submission/);
  expect(screen.queryByText("Current research run")).toBeNull();
  expect(screen.queryByText(/Email 1:/)).toBeNull();
});
