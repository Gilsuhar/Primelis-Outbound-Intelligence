it("offers the explicitly bounded Choice Hotels continuation and submits its saved record ID", async () => {
  const continued = structuredClone(savedChoice);
  continued.id = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
  continued.automatic!.status = "RUNNING";
  continued.automatic!.stage = "EVIDENCE_VALIDATION";
  continued.automatic!.continuedResearch = {
    documentId: savedChoice.id,
    runId: savedChoice.automatic!.run!.id,
    sha256: "a".repeat(64),
    startingStage: "EVIDENCE_VALIDATION",
    candidateFactIds: ["account:4", "account:5", "account:6"],
  };
  let submittedBody: Record<string, unknown> | undefined;
  vi.stubGlobal(
    "fetch",
    vi.fn(async (_: string, init?: RequestInit) => {
      if (init?.method === "POST") {
        submittedBody = JSON.parse(String(init.body));
        return Response.json({ ok: true, document: continued });
      }
      return Response.json({ ok: true, aiReady: true, documents: [savedChoice] });
    }),
  );
  render(<InternalCompanyReview />);
  await screen.findByText("Current research run");
  fireEvent.change(screen.getByLabelText("Company name or domain"), {
    target: { value: "Choice Hotels" },
  });
  const option = await screen.findByLabelText(/Continue the saved Choice Hotels evidence/);
  fireEvent.click(option);
  fireEvent.click(screen.getByRole("button", { name: "Research" }));
  await screen.findByText(/Continuing saved evidence from run/);
  expect(submittedBody).toMatchObject({
    company: "Choice Hotels",
    continueResearchId: savedChoice.id,
  });
  expect(submittedBody).not.toHaveProperty("reuseResearchId");
  expect(submittedBody).not.toHaveProperty("image");
});

