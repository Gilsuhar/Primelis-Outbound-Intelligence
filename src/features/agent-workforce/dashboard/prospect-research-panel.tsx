"use client";
import React, { useEffect, useRef, useState } from "react";
import type { DashboardProspect, RunSummary } from "./contracts";
import { researchStages } from "../prospect-research-contracts";
const button =
  "min-h-11 rounded-xl border border-line bg-white px-4 py-2 text-sm font-semibold disabled:opacity-50";
const names = {
  COMPANY: "Company intelligence",
  SIMILARWEB: "Similarweb",
  SERP: "Brand SERP",
  CONTACT: "Contact intelligence",
  ASSESSMENT: "Opportunity assessment",
  REVIEW: "Research review",
};
export function ProspectResearchPanel({
  prospect,
  runs,
  onRefresh,
}: {
  prospect: DashboardProspect;
  runs: RunSummary[];
  onRefresh: () => void;
}) {
  const [notice, setNotice] = useState("");
  const [busy, setBusy] = useState(false);
  const mounted = useRef(true);
  const run = runs.find((r) => r.prospectResearch && prospect.runIds.includes(r.id));
  const research = run?.prospectResearch;
  async function request(runId?: string) {
    setBusy(true);
    try {
      const response = await fetch("/api/sales-agent/prospect-research", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(runId ? { runId } : { contactId: prospect.contact.hubspotRecordId }),
      });
      const result = await response.json();
      if (!response.ok || !result.ok) throw new Error(result.message ?? "Research unavailable");
      if (mounted.current) onRefresh();
      if (mounted.current)
        setNotice(
          result.records?.find((r: { issue?: string }) => r.issue)?.issue ??
            "Research scheduled. Refresh the workspace for persisted progress; eligibility stays unchanged.",
        );
    } catch (error) {
      if (mounted.current)
        setNotice(error instanceof Error ? error.message : "Research unavailable");
    } finally {
      if (mounted.current) setBusy(false);
    }
  }
  useEffect(() => {
    mounted.current = true;
    return () => {
      mounted.current = false;
    };
  }, []);
  // Authenticated Preview progression while the workspace is open. Unattended operation uses the secured worker.
  const activeRunId = research?.status === "RUNNING" ? run?.id : undefined;
  useEffect(() => {
    if (!activeRunId) return;
    const timer = setInterval(() => {
      void fetch("/api/sales-agent/prospect-research", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ runId: activeRunId }),
      }).catch(() => undefined);
    }, 20000);
    return () => clearInterval(timer);
  }, [activeRunId]);
  return (
    <section
      className="min-w-0 rounded-2xl border border-line bg-white p-4 sm:p-6"
      aria-label="Autonomous prospect research"
    >
      <div className="flex flex-wrap items-center justify-between gap-3">
        <h2 className="font-semibold">
          Prospect intelligence · {research?.status ?? "Not researched"}
        </h2>
        <button
          className={button}
          disabled={busy || prospect.plan.decision.status === "REJECTED"}
          onClick={() =>
            void request(research && research.status !== "STALE" ? run?.id : undefined)
          }
        >
          {busy
            ? "Scheduling…"
            : research && research.status !== "STALE"
              ? "Resume research"
              : "Research synced prospect"}
        </button>
      </div>
      <p className="mt-2 text-xs text-stone-600">
        HubSpot record {prospect.contact.hubspotRecordId}. Research does not verify employment,
        clear eligibility or unlock Draft Studio. No emails are generated by this workflow.
      </p>
      {notice && (
        <p role="status" className="mt-3 break-words text-sm">
          {notice}
        </p>
      )}
      {!research && (
        <p className="mt-3 text-sm">
          Start from this synchronized contact. Approved product knowledge and authorized live
          sources are required; missing providers will remain explicitly unavailable.
        </p>
      )}
      {research && (
        <>
          <p className="mt-3 text-xs">
            Updated {run?.updatedAt} · freshness expires {research.expiresAt}
          </p>
          <ol className="mt-4 grid gap-3 sm:grid-cols-2">
            {researchStages.map((stage) => {
              const state = research.stages[stage];
              return (
                <li key={stage} className="min-w-0 rounded-xl bg-stone-50 p-3 text-sm">
                  <h3 className="font-medium">
                    {names[stage]} · {state.status.replaceAll("_", " ")}
                  </h3>
                  <p className="mt-1 break-words text-xs">{state.detail}</p>
                  <p className="mt-1 text-xs">
                    Attempt {state.attempts}/3 ·{" "}
                    {state.finishedAt ?? state.startedAt ?? "Not started"}
                    {state.retryAt ? ` · retry after ${state.retryAt}` : ""}
                  </p>
                </li>
              );
            })}
          </ol>
          <div className="mt-5 space-y-4">
            {(["ACCOUNT", "PROSPECT"] as const).map((subject) => (
              <section key={subject}>
                <h3 className="font-semibold">
                  {subject === "ACCOUNT" ? "Company intelligence" : "Contact intelligence"}
                </h3>
                {!run?.research.facts.some((f) => f.subject === subject) && (
                  <p className="mt-2 text-sm">No source-validated findings available.</p>
                )}
                {run?.research.facts
                  .filter((f) => f.subject === subject)
                  .map((f) => (
                    <article key={f.id} className="mt-3 border-l-2 border-line pl-3 text-sm">
                      <p>{f.statement}</p>
                      <p className="mt-1 text-xs">
                        {f.category} · {f.confidence} confidence · {f.limitations.join("; ")}
                      </p>
                      {f.quotes.map((q, i) => {
                        const source = run.research.sources.find((s) => s.id === q.sourceId);
                        return source ? (
                          <p key={i} className="mt-1 break-words text-xs">
                            <a
                              href={source.url}
                              target="_blank"
                              rel="noreferrer"
                              className="text-signal underline"
                            >
                              {source.title}
                            </a>{" "}
                            · retrieved {source.observedAt}
                            <br />
                            Quote: “{q.text}”
                          </p>
                        ) : null;
                      })}
                    </article>
                  ))}
              </section>
            ))}
          </div>
          <section className="mt-5">
            <h3 className="font-semibold">Similarweb · DATA UNAVAILABLE</h3>
            <p className="mt-2 text-sm">{research.similarweb.requiredAccess}</p>
          </section>
          <section className="mt-5">
            <h3 className="font-semibold">Observed brand SERPs</h3>
            {!research.serp.length && (
              <p className="mt-2 text-sm">
                No authorized observation collected. Query suggestions are not verified findings.
              </p>
            )}
            {research.serp.map((s) => (
              <article key={s.id} className="mt-3 text-sm">
                <p>
                  {s.query} · {s.location} · {s.country} · {s.device} · {s.observedAt}
                </p>
                <p>
                  Brand advertising: {s.brandAdvertising}. Other advertiser domains:{" "}
                  {s.otherAdvertiserDomains.join(", ") || "None observed in this snapshot"}.
                </p>
                <p className="mt-1">{s.limitation}</p>
                <a
                  href={s.sourceUrl}
                  target="_blank"
                  rel="noreferrer"
                  className="text-signal underline"
                >
                  Observed search source
                </a>
                <p className="mt-2">
                  Recommended capture (not a screenshot): {s.captureRecommendation}
                </p>
              </article>
            ))}
          </section>
          <section className="mt-5">
            <h3 className="font-semibold">Opportunity hypothesis</h3>
            {research.opportunity &&
            research.status !== "STALE" &&
            research.stages.REVIEW.status === "COMPLETE" ? (
              <div className="mt-2 space-y-2 text-sm">
                <p>{research.opportunity.hypothesis}</p>
                <p>
                  Recommended angle: {research.opportunity.recommendedAngle.replaceAll("_", " ")} ·{" "}
                  {research.opportunity.confidence} confidence
                </p>
                <p>
                  Evidence:{" "}
                  {[
                    ...research.opportunity.supportingFactIds,
                    ...research.opportunity.supportingObservationIds,
                  ].join(", ")}
                </p>
                {[
                  ...research.opportunity.limitations,
                  ...research.opportunity.missingInformation,
                ].map((s, i) => (
                  <p key={i}>Limitation / missing: {s}</p>
                ))}
                {research.opportunity.followUp.map((s, i) => (
                  <p key={i}>Suggested follow-up: {s}</p>
                ))}
              </div>
            ) : (
              <p className="mt-2 text-sm">
                No reviewed opportunity available. Missing or rejected evidence remains unresolved.
              </p>
            )}
          </section>
          <details className="mt-5 text-xs">
            <summary className="min-h-11 cursor-pointer font-semibold">
              Agent execution history
            </summary>
            <ol className="space-y-2">
              {research.history.map((event, i) => (
                <li key={i}>
                  {event.at} · {names[event.stage]} · {event.state}
                  {event.code ? ` · ${event.code}` : ""}
                </li>
              ))}
            </ol>
          </details>
          {[...run!.research.assumptions, ...run!.research.gaps, ...research.reviewIssues].map(
            (s, i) => (
              <p key={i} className="mt-2 break-words text-xs text-amber-900">
                Inference / missing evidence / review concern: {s}
              </p>
            ),
          )}
        </>
      )}
    </section>
  );
}
